use everust_core::event::{EventRecord, EventType};
use everust_core::finding::{Finding, FindingSeverity};
use everust_core::record::FlightRecording;
use std::collections::HashMap;

/// Configuration thresholds for deterministic anomaly analysis.
#[derive(Debug, Clone)]
pub struct AnalyzerConfig {
    /// Threshold in nanoseconds for flagging a synchronous poll as excessive.
    /// Default: 5ms (5,000,000 ns).
    pub long_poll_threshold_ns: u64,
    /// Threshold in nanoseconds for flagging lock acquisition latency as severe contention.
    /// Default: 1ms (1,000,000 ns).
    pub lock_contention_threshold_ns: u64,
    /// Threshold in nanoseconds between TaskWake and subsequent TaskPoll.
    /// Default: 10ms (10,000,000 ns).
    pub task_starvation_threshold_ns: u64,
}

impl Default for AnalyzerConfig {
    fn default() -> Self {
        Self {
            long_poll_threshold_ns: 5_000_000,       // 5 ms
            lock_contention_threshold_ns: 1_000_000, // 1 ms
            task_starvation_threshold_ns: 10_000_000, // 10 ms
        }
    }
}

/// Diagnostic report generated by analyzing an `.evr` flight recording.
#[derive(Debug, Clone)]
pub struct AnalysisReport {
    pub findings: Vec<Finding>,
    pub total_events: usize,
    pub total_tasks_observed: usize,
    pub contested_locks_count: usize,
}

/// Deterministic analysis engine.
pub struct Analyzer {
    config: AnalyzerConfig,
}

impl Analyzer {
    pub fn new(config: AnalyzerConfig) -> Self {
        Self { config }
    }

    /// Analyzes an entire `FlightRecording` and returns structured findings.
    pub fn analyze(&self, recording: &FlightRecording) -> AnalysisReport {
        self.analyze_events(&recording.events)
    }

    /// Analyzes a slice of raw `EventRecord`s.
    pub fn analyze_events(&self, events: &[EventRecord]) -> AnalysisReport {
        let mut findings = Vec::new();
        let mut observed_tasks = HashMap::new();
        let mut wake_timestamps: HashMap<u64, u64> = HashMap::new();
        let mut contested_locks = HashMap::new();

        for record in events {
            match &record.event {
                EventType::TaskSpawn { task_id, name } => {
                    observed_tasks.insert(*task_id, name.clone());
                }

                EventType::TaskWake { task_id } => {
                    wake_timestamps.insert(*task_id, record.timestamp_ns);
                }

                EventType::TaskPoll { task_id, elapsed_ns } => {
                    observed_tasks.entry(*task_id).or_insert(None);

                    // Check for Task Starvation (Wake -> Poll delay)
                    if let Some(wake_ts) = wake_timestamps.remove(task_id) {
                        let scheduling_delay_ns = record.timestamp_ns.saturating_sub(wake_ts);
                        if scheduling_delay_ns >= self.config.task_starvation_threshold_ns {
                            let delay_ms = scheduling_delay_ns as f64 / 1_000_000.0;
                            findings.push(
                                Finding::new(
                                    "EVERUST-T02",
                                    format!("Task #{} Starvation in Run Queue", task_id),
                                    format!(
                                        "Task #{} waited {:.2}ms between wake notification and poll execution. Worker threads were saturated.",
                                        task_id, delay_ms
                                    ),
                                    FindingSeverity::Warning,
                                    record.timestamp_ns,
                                )
                                .with_task(*task_id)
                                .with_duration(scheduling_delay_ns),
                            );
                        }
                    }

                    // Check for Long Task Poll
                    if *elapsed_ns >= self.config.long_poll_threshold_ns {
                        let elapsed_ms = *elapsed_ns as f64 / 1_000_000.0;
                        findings.push(
                            Finding::new(
                                "EVERUST-T01",
                                format!("Long Task Poll on Task #{}", task_id),
                                format!(
                                    "Task #{} executed uninterrupted for {:.2}ms without yielding. Exceeded 5ms cooperative threshold.",
                                    task_id, elapsed_ms
                                ),
                                FindingSeverity::Critical,
                                record.timestamp_ns,
                            )
                            .with_task(*task_id)
                            .with_duration(*elapsed_ns),
                        );
                    }
                }

                EventType::LockAcquire {
                    lock_id,
                    task_id,
                    wait_ns,
                } => {
                    contested_locks.insert(*lock_id, true);

                    if *wait_ns >= self.config.lock_contention_threshold_ns {
                        let wait_ms = *wait_ns as f64 / 1_000_000.0;
                        findings.push(
                            Finding::new(
                                "EVERUST-L01",
                                format!("High Lock Contention on Lock #{}", lock_id),
                                format!(
                                    "Task #{} stalled for {:.2}ms waiting to acquire Lock #{}. Mutex held by concurrent worker.",
                                    task_id, wait_ms, lock_id
                                ),
                                FindingSeverity::Critical,
                                record.timestamp_ns,
                            )
                            .with_task(*task_id)
                            .with_lock(*lock_id)
                            .with_duration(*wait_ns),
                        );
                    }
                }

                EventType::BlockingOperation {
                    task_id,
                    name,
                    duration_ns,
                } => {
                    let dur_ms = *duration_ns as f64 / 1_000_000.0;
                    findings.push(
                        Finding::new(
                            "EVERUST-B01",
                            format!("Synchronous Blocking Call: {}", name),
                            format!(
                                "Task #{} invoked blocking operation '{}' lasting {:.2}ms on an async runtime worker thread.",
                                task_id, name, dur_ms
                            ),
                            FindingSeverity::Critical,
                            record.timestamp_ns,
                        )
                        .with_task(*task_id)
                        .with_duration(*duration_ns),
                    );
                }

                _ => {}
            }
        }

        AnalysisReport {
            findings,
            total_events: events.len(),
            total_tasks_observed: observed_tasks.len(),
            contested_locks_count: contested_locks.len(),
        }
    }
}
